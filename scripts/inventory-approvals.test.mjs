import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
import {randomUUID} from 'node:crypto';
import {changeApprovalFixture,seedChangeApproval} from './helpers/change-approval-fixture.mjs';
const require=createRequire(import.meta.url);
const {registerInventoryMovementRoutes}=require('../backend/dist/services/inventoryMovements');
const {registerMaterialItem}=require('../backend/dist/services/materialItems');
const {saveApprovalActionBatch}=require('../backend/dist/services/approvalActions');

test('inventory approval lines, final-only stock, independent deletion, physical purge and retries',async()=>{
 const f=await changeApprovalFixture();try{
  const db=f.db,s=await seedChangeApproval(db),org=s.company.id,actor=s.people.junior.id,reviewer=s.people.admin.id;
  const unit=await db.expenseUnit.create({data:{code:'INV',nameEn:'Each',nameKo:'개',nameVi:'Cái'}});
  const base=await db.transactionCodeBase.findUnique({where:{id:s.code.baseId}});
  await db.accountingCodeIndustry.upsert({where:{baseId_systemIndustryId:{baseId:base.id,systemIndustryId:base.serviceTypeId}},create:{baseId:base.id,systemIndustryId:base.serviceTypeId},update:{}});
  const industry=await db.settingServiceDefault.update({where:{id:base.serviceTypeId},data:{materialManagement:true,materialManagementRevision:{increment:1}}});
  const configured=await db.transactionCodeBase.update({where:{id:base.id},data:{materialUnitId:unit.id,materialSettings:{enabled:true,stockFields:['unit'],unitInput:'REQUIRED',colorInput:'HIDDEN',masterInputs:{owner:'REQUIRED',color:'HIDDEN',type:'HIDDEN'}},materialRevision:{increment:1}}});
  const master=await db.$transaction(tx=>registerMaterialItem(tx,org,actor,{clientKey:randomUUID(),baseId:base.id,unitId:unit.id,sharedMaster:true,details:{},policyAuditId:null,materialRevision:configured.materialRevision,industryRevision:industry.materialManagementRevision}));
  const routes=new Map();registerInventoryMovementRoutes({get:(p,h)=>routes.set('GET '+p,h),post:(p,h)=>routes.set('POST '+p,h)},db,async req=>({orgId:req.orgId??org,actorId:req.actorId??actor}));
  const call=async(method,path,req={})=>{let result;await routes.get(method+' '+path)({query:{},params:{},...req},{status(){return this;},json(value){result=value;}});return result;};
  await assert.rejects(call('GET','/inventory-entry/approval-preview'),/INVENTORY_APPROVAL_NOT_CONFIGURED/);
  const settings={revision:0,drafterRoles:['ACCOUNTANT'],approverIds:[s.people.senior.id,reviewer]};
  await saveApprovalActionBatch(db,org,reviewer,['CREATE','DELETE'].map(operation=>({menu:'INVENTORY',operation,settings})));
  await assert.rejects(saveApprovalActionBatch(db,org,reviewer,[{menu:'INVENTORY',operation:'CREATE',settings}]),/APPROVAL_SETTINGS_CHANGED/);
  const receipt={clientKey:randomUUID(),masterId:master.id,ownerId:org,dimensions:{},date:'2026-11-20',quantity:'10',remark:'Receive',approvalRevision:1};
  await assert.rejects(call('POST','/inventory-entry',{body:{...receipt,clientKey:randomUUID(),approvalRevision:0}}),/APPROVAL_SETTINGS_CHANGED/);
  assert.equal((await db.$queryRaw`SELECT * FROM "InventoryMovement" WHERE "orgId"=${org}`).length,0);
  assert.equal((await db.$queryRaw`SELECT * FROM "InventoryVariant" WHERE "orgId"=${org}`).length,0);
  await assert.rejects(saveApprovalActionBatch(db,org,reviewer,[{menu:'INVENTORY',operation:'CREATE',settings:{...settings,revision:1}},{menu:'INVENTORY',operation:'DELETE',settings:{...settings,revision:1,approverIds:[999999]}}]),/INVENTORY_INVALID_POLICY/);
  assert.equal((await db.systemSetting.findUnique({where:{key:`APPROVAL_POLICY:INVENTORY:CREATE:${org}`}})).value.revision,1);
  const submitted=await call('POST','/inventory-entry',{body:receipt});
  assert.deepEqual(await call('POST','/inventory-entry',{body:receipt}),submitted);
  await assert.rejects(call('POST','/inventory-entry',{body:{...receipt,quantity:'11'}}),/INVENTORY_RETRY_MISMATCH/);
  assert.deepEqual(await call('GET','/inventory-entry/stock'),[]);
  let [pending]=await call('GET','/inventory-entry/approvals');
  const decide=(actorId,revision,decision='APPROVED')=>call('POST','/inventory-entry/approvals/:id/decision',{actorId,params:{id:pending.id},body:{revision,decision}});
  await assert.rejects(decide(actor,1),/INVENTORY_APPROVAL_FORBIDDEN/);
  await assert.rejects(decide(reviewer,1),/INVENTORY_APPROVAL_FORBIDDEN/);
  await decide(s.people.senior.id,1);
  assert.deepEqual(await call('GET','/inventory-entry/stock'),[]);
  await assert.rejects(decide(reviewer,1),/INVENTORY_MOVEMENT_CHANGED/);
  await decide(reviewer,2);
  assert.equal((await call('GET','/inventory-entry/stock'))[0].quantity,'10.0000');
  const history=await call('GET','/inventory-entry/history');assert.equal(history[0].status,'APPROVED');
  const deleteBody={clientKey:randomUUID(),revision:history[0].revision,approvalRevision:1};
  const requestDelete=body=>call('POST','/inventory-entry/:id/delete-request',{params:{id:submitted.id},body});
  const deletion=await requestDelete(deleteBody);
  assert.deepEqual(await requestDelete(deleteBody),deletion);
  assert.equal((await call('GET','/inventory-entry/stock')).length,1);
  [pending]=await call('GET','/inventory-entry/approvals');
  await decide(s.people.senior.id,1);await decide(reviewer,2);
  assert.deepEqual(await call('GET','/inventory-entry/history'),[]);
  assert.deepEqual(await call('GET','/inventory-entry/stock'),[]);
  assert.equal((await db.$queryRaw`SELECT * FROM "InventoryVariant" WHERE "orgId"=${org}`).length,0);
  assert.equal((await db.$queryRaw`SELECT * FROM "InventoryApprovalRequest" WHERE "orgId"=${org} AND "movementId" IS NULL`).length,2);
  assert.deepEqual(await call('POST','/inventory-entry',{body:receipt}),submitted);
  assert.deepEqual(await call('GET','/inventory-entry/history'),[]);
  assert.deepEqual(await requestDelete(deleteBody),deletion);
  await assert.rejects(call('POST','/inventory-entry/approvals/:id/decision',{orgId:s.other.id,actorId:reviewer,params:{id:deletion.id},body:{revision:2,decision:'APPROVED'}}),/INVENTORY_APPROVAL_NOT_FOUND/);
  await assert.rejects(call('GET','/inventory-entry/approval-preview',{actorId:s.people.senior.id}),/INVENTORY_SELF_APPROVAL/);
  const fresh=await call('POST','/inventory-entry',{body:{...receipt,clientKey:randomUUID()}});
  await assert.rejects(db.$executeRaw`DELETE FROM "InventoryMovement" WHERE id=${fresh.id}`,/approval required/);
  await assert.rejects(db.$executeRaw`UPDATE "InventoryMovement" SET status='APPROVED',revision=revision+1 WHERE id=${fresh.id}`,/approval mismatch/);
  const freshDelete=await call('POST','/inventory-entry/:id/delete-request',{params:{id:fresh.id},body:{clientKey:randomUUID(),revision:1,approvalRevision:1}});
  pending={id:fresh.id};await assert.rejects(decide(s.people.senior.id,1),/INVENTORY_DELETE_PENDING/);
  pending=freshDelete;await decide(s.people.senior.id,1,'REJECTED');
  assert.equal((await call('GET','/inventory-entry/history'))[0].status,'PENDING');
  const retryDelete=await call('POST','/inventory-entry/:id/delete-request',{params:{id:fresh.id},body:{clientKey:randomUUID(),revision:1,approvalRevision:1}});
  pending=retryDelete;await decide(s.people.senior.id,1);await decide(reviewer,2);
  assert.equal((await db.$queryRaw`SELECT status FROM "InventoryApprovalRequest" WHERE id=${fresh.id}`)[0].status,'CANCELLED');
  assert.deepEqual(await call('GET','/inventory-entry/history'),[]);
  const rejected=await call('POST','/inventory-entry',{body:{...receipt,clientKey:randomUUID()}});
  pending=rejected;await decide(s.people.senior.id,1,'REJECTED');
  assert.equal((await call('GET','/inventory-entry/history'))[0].status,'REJECTED');
  assert.deepEqual(await call('GET','/inventory-entry/stock'),[]);
  await db.employee.update({where:{id:reviewer},data:{status:'SUSPENDED'}});
  await assert.rejects(call('GET','/inventory-entry/approval-preview'),/INVENTORY_APPROVER_UNAVAILABLE/);
  await db.employee.update({where:{id:reviewer},data:{status:'ACTIVE'}});
  const shared=await call('POST','/inventory-entry',{body:{...receipt,clientKey:randomUUID(),quantity:'5'}});
  pending=shared;await decide(s.people.senior.id,1);await decide(reviewer,2);
  const deleteShared=await call('POST','/inventory-entry/:id/delete-request',{params:{id:shared.id},body:{clientKey:randomUUID(),revision:2,approvalRevision:1}});
  pending=deleteShared;await decide(s.people.senior.id,1);await decide(reviewer,2);
  assert.equal((await db.$queryRaw`SELECT * FROM "InventoryVariant" WHERE "orgId"=${org}`).length,1,'a variant referenced by another movement must survive');
  assert.equal((await call('GET','/inventory-entry/history')).length,1);
  assert.deepEqual(await call('GET','/inventory-entry/stock'),[]);
  const migration=readFileSync('backend/prisma/migrations/20261120050000_inventory_approvals/migration.sql','utf8');await f.pg.exec(migration);await f.pg.exec(migration);
  await assert.rejects(db.$executeRaw`DELETE FROM "InventoryApprovalStep" WHERE "requestId"=${deletion.id}`,/immutable/);
 }finally{await f.close();}
});
