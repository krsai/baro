// Legacy single-language entries retain their original text; custom meanings are never translated by guesswork.
export function normalizeTextAcronymEntry(row,enrich=false){
 const base=defaultTextAcronyms.find(item=>item.acronym.toUpperCase()===String(row.acronym||'').toUpperCase());
 const legacy=typeof row.meaning==='string'?row.meaning:'';
 const known=enrich&&base&&(!legacy||legacy===base.meaningKo);
 const meaningKo=typeof row.meaningKo==='string'?row.meaningKo:legacy||(known?base.meaningKo:'');
 return {acronym:row.acronym,expansion:row.expansion||'',meaning:meaningKo,meaningKo,
  meaningEn:typeof row.meaningEn==='string'?row.meaningEn:known?base.meaningEn:'',
  meaningVi:typeof row.meaningVi==='string'?row.meaningVi:known?base.meaningVi:''};
}
